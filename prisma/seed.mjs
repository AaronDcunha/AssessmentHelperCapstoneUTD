import { randomBytes, scryptSync } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import pg from 'pg';
import { buildSeed, stableId, rolePermissions } from './seed-data.mjs';

// No database access occurs during --dry-run. The login reference is reproducible.
const dryRun = process.argv.includes('--dry-run');
if (process.argv.some(a => a.startsWith('--') && a !== '--dry-run')) throw new Error('Unknown seed option');
if (!dryRun && process.env.NODE_ENV === 'production') throw new Error('Demo seeding is disabled in production');
const { tables, accounts, skipped } = buildSeed();
const examples = ['Faculty','Admin','AC'].map(role => {
  const account = accounts.find(a => role === 'Faculty' ? a.roles.length === 1 : a.roles.includes(role));
  if (!account) throw new Error(`Missing example for ${role}`);
  return `${role}: ${account.fullName}\nUsername: ${account.username}\nEmail: ${account.email}\nPassword: 123\nRoles: ${account.roles.join(', ')}`;
});
const reference = `LOCAL DEMO ACCOUNTS\nGenerated by npm run db:seed or npm run db:seed:preview.\nThese accounts exist in the database only after a successful seed.\nLogin is not implemented yet.\nAccess: Faculty; AC includes Faculty; Admin includes AC and Faculty.\n\n${examples.join('\n\n')}\n`;

async function seed() {
  if (!process.env.DATABASE_URL) throw new Error('Set DATABASE_URL in .env');
  const url = new URL(process.env.DATABASE_URL);
  // pg does not interpret Prisma's schema URL option.
  const schema = url.searchParams.get('schema') || 'public';
  if (schema !== 'public') throw new Error('This demo seed currently supports schema=public only');
  url.searchParams.delete('schema');
  const client = new pg.Client({connectionString:url.toString(),connectionTimeoutMillis:10000});
  await client.connect();
  try {
    await client.query('BEGIN');
    await client.query("SET LOCAL search_path TO public");
    await client.query("SET LOCAL lock_timeout = '10s'");
    await client.query("SELECT pg_advisory_xact_lock(hashtext('assessment-helper-demo-seed-v1'))");
    // Table/column identifiers below come exclusively from code, never source data.
    async function upsert(table, rows, conflict, updateColumns) {
      if (!rows.length) return;
      const columns = Object.keys(rows[0]);
      const quote = value => '"' + value.replaceAll('"','""') + '"';
      const updates = updateColumns ?? columns.filter(c => !conflict.includes(c));
      for (let offset = 0; offset < rows.length; offset += 500) {
        const chunk = rows.slice(offset,offset+500), values = [];
        const tuples = chunk.map(row => '(' + columns.map(column => {values.push(row[column]);return '$'+values.length;}).join(',') + ')');
        const action = updates.length ? 'DO UPDATE SET '+updates.map(c=>`${quote(c)}=EXCLUDED.${quote(c)}`).join(',') : 'DO NOTHING';
        await client.query(`INSERT INTO ${quote(table)} (${columns.map(quote).join(',')}) VALUES ${tuples.join(',')} ON CONFLICT (${conflict.map(quote).join(',')}) ${action}`,values);
      }
    }
    const keys = {department:['department_id'],hiring_level:['hiring_level_id'],semester:['semester_id'],course:['course_id'],app_user:['user_id'],professor:['professor_id'],course_section:['section_id'],teaches:['professor_id','section_id'],class_meeting:['meeting_id'],evaluation_cycle:['cycle_id'],observation_template:['template_id'],template_criterion:['criterion_id']};
    for (const [table,rows] of Object.entries(tables)) {
      // Keep AC edits to the demo cycle/template/questions when rerunning the seed.
      const preserve = ['evaluation_cycle','observation_template','template_criterion'].includes(table);
      await upsert(table,rows,keys[table],preserve ? [] : undefined);
    }
    await upsert('role',['Faculty','Admin','AC'].map(name=>({role_id:stableId(`role:${name}`),role_name:name})),['role_id']);
    await upsert('permission',[...new Set(Object.values(rolePermissions).flat())].map(name=>({permission_id:stableId(`permission:${name}`),permission_name:name})),['permission_id']);
    await upsert('role_permission',Object.entries(rolePermissions).flatMap(([role,permissions])=>permissions.map(name=>({role_id:stableId(`role:${role}`),permission_id:stableId(`permission:${name}`)}))),['role_id','permission_id'],[]);
    const credentials = accounts.map(a => {
      const salt = randomBytes(16).toString('hex');
      const hash = scryptSync('123',salt,64).toString('hex');
      return {credential_id:stableId(`credential:${a.username}`),user_id:a.userId,password_hash:`scrypt:${salt}:${hash}`};
    });
    // Preserve password changes and additional role assignments on subsequent runs.
    await upsert('login_credential',credentials,['user_id'],[]);
    await upsert('user_role',accounts.flatMap(a=>a.roles.map(role=>({user_id:a.userId,role_id:stableId(`role:${role}`)}))),['user_id','role_id'],[]);
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally { await client.end(); }
}

if (!dryRun) await seed();
writeFileSync(new URL('./demo-accounts.txt',import.meta.url),reference);
console.log(JSON.stringify({mode:dryRun?'preview (database unchanged)':'seeded',skipped,counts:Object.fromEntries(Object.entries(tables).map(([k,v])=>[k,v.length])),roles:Object.fromEntries(['Faculty','Admin','AC'].map(role=>[role,accounts.filter(a=>a.roles.includes(role)).length])),loginReference:'prisma/demo-accounts.txt',permissions:Object.fromEntries(Object.entries(rolePermissions).map(([role,permissions])=>[role,permissions.length]))},null,2));
